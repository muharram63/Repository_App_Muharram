    private array $names = ['Фарход', 'Шаҳло', 'Далер', 'Нигина', 'Бахтиёр', 'Мадина', 'Сомон', 'Зарина', 'Рустам', 'Парвина'];

    private array $surnames = ['Раҳимов', 'Назаров', 'Каримов', 'Саидов', 'Шарипов', 'Юсупов', 'Ҳамидов', 'Мирзоев'];

    public function run(): void
    {
        if (DB::table('users')->where('email', 'like', '%'.self::MAIL)->exists()) {
            $this->command->warn('Вакансии по профессиям уже загружены — повторно не создаю.');

            return;
        }

        $now = now();
        $password = Hash::make('password');

        DB::transaction(function () use ($now, $password) {
            $employers = $this->seedCompanies($now, $password);
            $count = $this->seedVacancies($employers, $now);

            $this->command->info('Готово: '.count($employers).' компаний, '.$count.' вакансий по '.count($this->professions).' профессиям.');
        });
    }

    /** @return array<string,array{id:int,city:int,name:string}> */
    private function seedCompanies($now, string $password): array
    {
        $result = [];
        $i = 0;

        foreach ($this->companies as $key => [$name, $city, $categoryName, $industryName, $about]) {
            $i++;
            $email = 'hr'.$i.self::MAIL;

            $cityId = City::firstOrCreate(['region' => $city], ['country' => 'Таджикистан'])->id;
            $categoryId = Category::firstOrCreate(
                ['name' => $categoryName],
                ['description' => 'Вакансии и компании направления «'.$categoryName.'»', 'slug' => Str::slug($categoryName)]
            )->id;
            $industryId = Industry::firstOrCreate(
                ['name' => $industryName],
                ['category_id' => $categoryId, 'parent_id' => 0, 'description' => 'Отрасль «'.$industryName.'»']
            )->id;

            $userId = DB::table('users')->insertGetId([
                'name' => $this->names[$i % count($this->names)].' '.$this->surnames[$i % count($this->surnames)],
                'email' => $email,
                'password' => $password,
                'role' => 'employer',
                'status' => 'active',
                'theme' => 'light',
                'date_register' => $now->copy()->subDays(60 + $i * 7)->format('Y-m-d'),
                'created_at' => $now->copy()->subDays(60 + $i * 7),
                'updated_at' => $now,
            ]);

            $employerId = DB::table('employers')->insertGetId([
                'logo' => null,
                'user_id' => $userId,
                'company_name' => $name,
                'job' => 'Менеджер по персоналу',
                'email_company' => 'jobs'.$i.self::MAIL,
                'phone' => '+992 '.(37 + $i % 8).' '.(200 + $i * 13).'-'.(10 + $i).'-'.(20 + $i),
                'category_id' => $categoryId,
                'description' => $name.' '.$about.'. Мы растём и ищем в команду людей, которые хотят развиваться вместе с нами: '
                    .'официальное оформление, зарплата без задержек и обучение за счёт компании.',
                'city_id' => $cityId,
                'industry_id' => $industryId,
                'website_url' => '',
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            $result[$key] = ['id' => $employerId, 'city' => $cityId, 'name' => $name];
        }

        return $result;
    }

    private function seedVacancies(array $employers, $now): int
    {
        $rows = [];
        $n = 0;

        foreach ($this->professions as [$title, $companyKeys, $skills, $duties, $requirements, [$from, $to], $experience, $schedule]) {
            foreach ($companyKeys as $j => $key) {
                $company = $employers[$key];
                // у разных компаний одна профессия стоит по-разному
                $shift = $j * 500;
                $n++;

                $rows[] = [
                    'title' => $title,
                    'description' => $this->description($company['name'], $title, $duties, $requirements),
                    'employer_id' => $company['id'],
                    'salary_from' => $from + $shift,
                    'salary_to' => $to + $shift,
                    'currency' => 'TJS',
                    'employment_type' => $j === 2 && $schedule === 'flexible_schedule' ? 'part-time' : 'full-time',
                    'work_schedule' => $schedule,
                    'experience_required' => $experience,
                    'skill' => $skills,
                    'languages' => $n % 3 === 0 ? 'Тоҷикӣ, Русӣ, Англисӣ' : 'Тоҷикӣ, Русӣ',
                    'status' => 'active',
                    'views' => 0,
                    'city_id' => $company['city'],
                    'created_by' => $company['id'],
                    'created_at' => $now->copy()->subDays(($n * 3) % 45)->subHours($n % 24),
                    'updated_at' => $now,
                ];
            }
        }

        DB::table('vacancies')->insert($rows);

        return count($rows);
    }

    private function description(string $company, string $title, array $duties, array $requirements): string
    {
        return $company.' ищет сотрудника на должность «'.$title.'».'
            ."\n\nОбязанности:\n— ".implode(";\n— ", $duties).'.'
            ."\n\nТребования:\n— ".implode(";\n— ", $requirements).'.'
            ."\n\nМы предлагаем:"
            ."\n— официальное трудоустройство;"
            ."\n— зарплату два раза в месяц без задержек;"
            ."\n— обучение и испытательный срок с полной оплатой;"
            ."\n— дружный коллектив и возможность роста.";
    }
