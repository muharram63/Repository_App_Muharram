<?php

namespace Database\Seeders;

use App\Models\Skill;
use Illuminate\Database\Seeder;

/**
 * Стартовый справочник навыков.
 *
 * Намеренно не только про разработку: смысл проверки навыков в том, чтобы
 * доказать умение мог продавец, бухгалтер или водитель, а не только тот,
 * у кого есть диплом по информатике.
 */
class SkillsSeeder extends Seeder
{
    public function run(): void
    {
        $catalogue = [
            'Разработка' => ['PHP', 'Laravel', 'JavaScript', 'Python', 'SQL', 'HTML и CSS', 'Git'],
            'Данные и аналитика' => ['Excel', 'Google Таблицы', 'Анализ данных', '1С'],
            'Продажи и клиенты' => ['Продажи по телефону', 'Работа с возражениями', 'Клиентская поддержка', 'CRM'],
            'Управление' => ['Управление проектами', 'Планирование задач', 'Работа в команде'],
            'Финансы' => ['Бухгалтерский учёт', 'Первичная документация', 'Финансовая отчётность'],
            'Языки' => ['Английский язык', 'Русский язык'],
            'Дизайн и контент' => ['Графический дизайн', 'Копирайтинг', 'SMM'],
        ];

        foreach ($catalogue as $area => $skills) {
            foreach ($skills as $name) {
                Skill::firstOrCreate(['name' => $name], ['area' => $area]);
            }
        }
    }
}
