<?php

namespace App\Support;

/**
 * Правдоподобное число просмотров для демо-записей.
 *
 * Случайное число выдавало нелепицу: у вакансии стояло «372 просмотра»,
 * хотя её никто не открывал. Ноль оказался не лучше — у вакансии с четырнадцатью
 * откликами просмотров не может быть ноль, ведь каждый откликнувшийся сначала
 * её открыл.
 *
 * Поэтому считаем от реальной активности: сколько откликов пришло, столько
 * человек точно заходили, плюс те, кто посмотрел и не откликнулся. Цифра
 * остаётся скромной — витрина не должна изображать посещаемость, которой нет.
 */
class DemoViews
{
    /** Выше этого не поднимаемся: демо-площадка, а не работающий портал. */
    public const CEILING = 37;

    /**
     * Просмотры по числу откликов.
     *
     * На каждый отклик приходится несколько заходов: кто-то открыл, прочитал
     * и закрыл. Соотношение взято скромное, чтобы цифра оставалась похожей
     * на правду для площадки, которая только запускается.
     */
    public static function forResponses(int $responses): int
    {
        $lookers = random_int(2, 9);

        return min(self::CEILING, $responses * random_int(2, 4) + $lookers);
    }
}
