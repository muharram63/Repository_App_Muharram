<?php

namespace App\Support;

/**
 * Сколько запросов сервер обрабатывает одновременно.
 *
 * `php artisan serve` — это встроенный сервер PHP (`php -S`), и на Windows он
 * обслуживает ровно один запрос за раз: PHP_CLI_SERVER_WORKERS там не
 * поддерживается. Для ИИ-собеседования это не мелочь. После каждого ответа
 * страница чата в фоне просила оценить ответ и составить задание — это
 * обращения к модели на десятки секунд, а составление и на минуты. Пока они
 * шли, сервер не принимал ничего: озвучка вопроса ждала за ними, микрофон не
 * включался, а кнопка «Отправить» висела. Со стороны это выглядело как
 * «кнопки не работают и голос не берёт».
 *
 * На таком сервере фоновую работу на время разговора откладываем: оценки
 * догонит очередь или страница задания, а задание составится, когда
 * кандидат до него дойдёт. Под Apache, nginx + FPM и на любом настоящем
 * сервере запросы идут параллельно, и всё работает как задумано.
 */
class ServerCapacity
{
    public static function singleThreaded(): bool
    {
        if (PHP_SAPI !== 'cli-server') {
            return false;
        }

        // на Linux и macOS `php -S` умеет несколько процессов
        return PHP_OS_FAMILY === 'Windows' || (int) getenv('PHP_CLI_SERVER_WORKERS') < 2;
    }
}
