 * Пороги и веса — это числа, которые кто-то однажды поставил. Пока их не
 * прогнали через набор заведомо разных людей, неизвестно, разделяют они хоть
 * что-нибудь или пропускают всех подряд. Здесь лежит такой набор: сильные,
 * слабые, пограничные, приукрасившие резюме и один, пытающийся управлять
 * оценкой.
 *
 * Профили — данные, а не тесты. Их гоняет CalibrationRunner: в тестах со
 * скриптованной моделью (проверяется, что правила разделяют людей) и командой
 * `ai:calibrate` на живой модели (проверяется, что так же делает и она).
 *
 * Про ответы честно: они заготовлены заранее, а вопросы формулирует модель, и
 * идеального попадания «ответ ровно на этот вопрос» тут нет. Ответы разложены
 * по критериям, и берётся тот, что относится к проверяемому требованию, — этого
 * достаточно, чтобы отличить «конкретно и с цифрами» от «общими словами», а
 * именно это и калибруется.
 */
class CalibrationProfiles
{
