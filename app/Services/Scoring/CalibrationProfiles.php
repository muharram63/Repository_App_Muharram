    private static function goodSolution(): string
    {
        return <<<'PHP'
            <?php

            function normalizePhone(string $raw): ?string
            {
                $digits = preg_replace('/\D+/', '', $raw);

                if ($digits === '') {
                    return null;
                }

                // местный формат: 9 цифр после кода страны 992
                if (strlen($digits) === 9) {
                    $digits = '992'.$digits;
                }

                if (str_starts_with($digits, '8') && strlen($digits) === 10) {
                    $digits = '992'.substr($digits, 1);
                }

                return strlen($digits) === 12 && str_starts_with($digits, '992')
                    ? '+'.$digits
                    : null;
            }
            PHP;
    }

    private static function decentSolution(): string
    {
        return <<<'PHP'
            <?php

            function normalizePhone(string $raw): ?string
