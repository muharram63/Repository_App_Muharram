<?php

namespace App\Services\Ai;

/**
 * Озвучка текста голосом.
 *
 * Отдельный интерфейс — по той же причине, что у помощника по резюме и разбора
 * совпадения: страница не должна знать о провайдере, а тесты — ходить в сеть и
 * тратить квоту на генерацию звука.
 *
 * Синтез принципиально необязателен. Если его нет — нет ключа, кончилась
 * квота, упал запрос, — собеседование идёт дальше: вопрос всегда есть текстом,
 * а браузер умеет прочитать его своим голосом. Поэтому available() спрашивают
 * заранее, а не узнают об отказе из исключения.
 */
interface SpeechSynthesizer
{
    public function available(): bool;

    /**
     * Голос, которым озвучиваем. Нужен снаружи для кэша: сменили голос —
     * прежние файлы больше не годятся.
     */
    public function voice(): string;

    /**
     * Озвучить текст.
     *
     * @return array{bytes:string,mime:string,tokens:int}
     *
     * @throws AiUnavailableException
     */
    public function speak(string $text): array;
}
