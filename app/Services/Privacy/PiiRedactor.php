<?php

namespace App\Services\Privacy;

/**
 * Вырезает из текста то, что не должно влиять на оценку кандидата.
 *
 * Пол, возраст, дата рождения, национальность, гражданство, религия, семейное
 * положение, здоровье и внешность к умению работать отношения не имеют, а
 * попав в промпт, влияют на ответ модели незаметно для всех. Поэтому текст
 * резюме и документов проходит через этот класс ДО оценочных вызовов.
 *
 * Про границы честно. Класс убирает то, что размечено или сказано прямо:
 * «Возраст: 34», «Пол: мужской», «мне 34 года», «женат», «гражданство РТ».
 * Свободное упоминание в середине рассказа он поймать не может и не пытается —
 * для этого пришлось бы угадывать смысл, а угадывание здесь опаснее пропуска:
 * вырезав «30 лет опыта» вместо «30 лет от рождения», мы испортили бы как раз
 * то, что и нужно оценивать.
 *
 * Поэтому защита двойная: этот класс снимает явное, а промпт отдельно
 * запрещает модели учитывать такие сведения, даже если они попались.
 */
class PiiRedactor
{
    /** Чем заменяем вырезанное. Видимая метка лучше пустоты: по ней понятно, что текст правили. */
    public const MASK = '[скрыто]';

    /**
     * Размеченные поля анкет: «Возраст: 34», «Пол — мужской».
     *
     * Ключи перечислены и по-русски, и по-английски: резюме на площадке
     * встречаются оба, и англоязычный шаблон «Date of birth:» не редкость.
     */
    private const LABELS = [
        'возраст', 'дата рождения', 'д\.р\.', 'день рождения', 'родился', 'родилась',
        'пол', 'национальность', 'гражданство', 'вероисповедание', 'религия',
        'семейное положение', 'семейный статус', 'дети', 'рост', 'вес',
        'инвалидность', 'группа инвалидности', 'состояние здоровья', 'диагноз',
        'фото', 'фотография', 'внешность',
        'age', 'date of birth', 'birth date', 'birthday', 'dob', 'gender', 'sex',
        'nationality', 'citizenship', 'religion', 'marital status', 'children',
        'height', 'weight', 'disability', 'health', 'photo',
    ];

    /**
     * Прямые высказывания о себе. Здесь важна привязка к слову-указателю:
     * «мне 34 года» вырезаем, «34 года опыта» оставляем.
     */
    private const STATEMENTS = [
        // мне 34 / мне 34 года / мне 34-й год
        '/\bмне\s+\d{1,2}\s*(год\w*|лет)?\b/ui',
        // 34 года от рождения, 34 года, полных лет
        '/\b\d{1,2}\s*(полных\s+)?(год\w*|лет)\s+(от\s+рождения|отроду)\b/ui',
        // I am 34 / I'm 34 years old
        '/\bI\s*(am|\x27m)\s+\d{1,2}(\s+years?\s+old)?\b/ui',
        // женат, замужем, холост, не замужем, разведён
        '/\b(женат|замужем|холост\w*|не\s+замужем|разведе\w+|вдов\w+)\b/ui',
        '/\b(married|single|divorced|widowed)\b/ui',
        // мужчина, женщина как самоописание
        '/\b(я|am)\s+(мужчина|женщина)\b/ui',
    ];

    /**
     * Даты рождения в свободном виде рядом со словом о рождении.
     * Отдельно от LABELS: там двоеточие, а здесь предлог.
     */
    private const BIRTH_DATES = [
        '/\b(родил\w+|рожден\w+|born)\s+(в\s+)?\d{1,2}[.\/-]\d{1,2}[.\/-]\d{2,4}\b/ui',
        '/\b(родил\w+|рожден\w+|born)\s+(в\s+)?\d{4}\s*(году|г\.)?/ui',
    ];

    /**
     * Очистить текст перед оценкой.
     */
    public function clean(?string $text): string
    {
        if (blank($text)) {
            return '';
        }

        $text = $this->stripLabels($text);
        $text = $this->stripPatterns($text, self::BIRTH_DATES);
        $text = $this->stripPatterns($text, self::STATEMENTS);

        // от вырезаний остаются двойные пробелы и осиротевшие запятые
        $text = preg_replace('/\s{2,}/u', ' ', $text) ?? $text;
        $text = preg_replace('/\s+([,;.])/u', '$1', $text) ?? $text;

        return trim($text);
    }

    /**
     * Очистить набор полей — резюме приходит массивом.
     *
     * @param  array<string,mixed>  $fields
     * @return array<string,mixed>
     */
    public function cleanFields(array $fields): array
    {
        foreach ($fields as $key => $value) {
            if (is_string($value)) {
                $fields[$key] = $this->clean($value);
            } elseif (is_array($value)) {
                $fields[$key] = $this->cleanFields($value);
            }
        }

        return $fields;
    }

    /**
     * Нашлось ли что-то, подлежащее сокрытию. Пригодится отчёту: работодатель
     * видит, что данные вырезаны, а не потерялись.
     */
    public function foundSomething(?string $text): bool
    {
        return $this->clean($text) !== trim((string) $text);
    }

    /** Сколько знаков захватываем как значение размеченного поля. */
    private const VALUE_LIMIT = 40;

    /**
     * Размеченные поля: ключ, разделитель, короткое значение.
     *
     * Границу значения приходится ставить осторожно, и это главное место, где
     * редактор может навредить. Сначала значение бралось до конца строки — и на
     * тексте, вытащенном из PDF одной строкой, «Возраст: 34. Пол: мужской. По
     * делу: 4 года на Laravel» целиком превращалось в метку: в промпт уходил
     * текст без опыта, и никто бы этого не заметил.
     *
     * Поэтому значение обрывается на конце предложения — точке с пробелом — и
     * ограничено длиной. Дата «12.05.1992» при этом остаётся целой: в ней после
     * точки пробела нет.
     */
    private function stripLabels(string $text): string
    {
        foreach (self::LABELS as $label) {
            $text = preg_replace(
                /*
                 * Где метка может стоять.
                 *
                 * Не только с начала строки: в тексте из PDF всё идёт одной
                 * строкой, а в резюме поля вкладывают друг в друга — «О себе:
                 * Возраст: 34, женат». Поэтому перед меткой допускается начало
                 * строки, перечислительный знак, конец предложения, двоеточие
                 * или запятая.
                 *
                 * Это сознательно расширенная сеть, и цена известна: фраза
                 * «средний возраст клиентов: 35 лет» тоже будет вырезана. Для
                 * этого модуля такой обмен правильный — потерянный обрывок
                 * предложения дешевле, чем возраст кандидата, дошедший до
                 * модели. Границу значения по-прежнему держат конец предложения
                 * и предел длины, поэтому съесть весь текст она не может.
                 */
                '/(^|[\n;|•·:,]|\.\s+)\s*'.$label.'\s*[:—–-]\s*'
                    // не пересекаем границу предложения и не жадничаем
                    .'(?:(?!\.\s|$)[^\n;|•·]){0,'.self::VALUE_LIMIT.'}/ui',
                '$1'.self::MASK,
                $text,
            ) ?? $text;
        }

        return $text;
    }

    /**
     * @param  array<int,string>  $patterns
     */
    private function stripPatterns(string $text, array $patterns): string
    {
        foreach ($patterns as $pattern) {
            $text = preg_replace($pattern, self::MASK, $text) ?? $text;
        }

        return $text;
    }

    /**
     * Строка для промпта: напоминание модели не учитывать такие сведения.
     *
     * Второй рубеж после вырезания. Нужен потому, что свободное упоминание
     * пройдёт мимо регулярных выражений, а решение всё равно должно строиться
     * только на умениях.
     */
    public const PROMPT_RULE = 'Пол, возраст, дату рождения, национальность, гражданство, религию, '
        .'семейное положение, здоровье и внешность кандидата не учитывай и не упоминай, даже если '
        .'они встретились в тексте. Оценивай только навыки, опыт, образование и результаты работы. '
        .'Метка '.self::MASK.' означает удалённые персональные данные — не пытайся их восстановить '
        .'и не делай о них предположений.';
}
