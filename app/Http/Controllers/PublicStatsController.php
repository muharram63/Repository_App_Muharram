<?php

namespace App\Http\Controllers;

use App\Support\PublicNumbers;

/**
 * Публичная страница статистики платформы.
 *
 * Открыта всем, в том числе гостям: цифры обезличенные, и именно они
 * показывают, что площадка живая, — что резюме читают, а отклики
 * заканчиваются выходом на работу.
 */
class PublicStatsController extends Controller
{
    public function index()
    {
        return view('public.pages.statistics', [
            'stats' => PublicNumbers::all(),
            'ttl' => PublicNumbers::TTL_MINUTES,
        ]);
    }

    /**
     * Список трудоустройств: куда и кем выходили люди.
     *
     * Открывается по клику на цифру «вышли на работу» — так видно, что за
     * числом стоят конкретные выходы на работу, а не просто счётчик.
     * Имён здесь нет намеренно: страница публичная, а связка «человек принят
     * в компанию» — сведения о его трудоустройстве. Профессии, компании
     * и месяца достаточно, чтобы число было проверяемым.
     */
    public function hired()
    {
        $hires = PublicNumbers::hires();

        return view('public.pages.hired', [
            'hires' => $hires,
            // число берём из самой выборки, а не из отдельного счётчика:
            // тогда заголовок и строки не разойдутся никогда
            'total' => $hires->total(),
        ]);
    }
}
